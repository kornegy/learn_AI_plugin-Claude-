// Bundles the MCP server and the two hook programs into ESM files in dist/.
// The output is committed: plugins are installed without a build step.
//
// The output is deliberately NOT minified. Reviewers and the plugin directory's security scan
// read the shipped code, so it must stay readable: every bundled module keeps its
// `// node_modules/<package>/<file>` or `// src/<file>` header. Code splitting puts the code
// that the three programs share into chunks/, which roughly halves the shipped size.
// THIRD_PARTY_NOTICES.md lists every bundled package with its license text.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import path from 'node:path';

const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8'));

rmSync('dist', { recursive: true, force: true });

const result = await build({
  entryPoints: {
    'mentor-mcp': 'src/mcp/main.ts',
    hook: 'src/hook/main.ts',
    nudge: 'src/hook/nudge.ts',
  },
  outdir: 'dist',
  outExtension: { '.js': '.mjs' },
  entryNames: '[name]',
  chunkNames: 'chunks/[name]-[hash]',
  bundle: true,
  splitting: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  minify: false,
  legalComments: 'eof',
  metafile: true,
  logLevel: 'info',
  define: { __MENTOR_VERSION__: JSON.stringify(pkg.version) },
  // Some dependencies use require(); give each ESM file a working require.
  banner: {
    js: "import { createRequire as __lmCreateRequire } from 'node:module'; const require = __lmCreateRequire(import.meta.url);",
  },
});

// THIRD_PARTY_NOTICES.md: the packages that actually ended up in dist/, with their licenses.
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
  if (m) packages.set(m[1], path.join('node_modules', m[1]));
}
const licenseFile = (dir) =>
  ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'LICENCE'].map((f) => path.join(dir, f)).find((f) => existsSync(f));
let notices =
  '# Third-party notices\n\n' +
  'The files in `server/dist/` bundle the following open-source packages. This file is generated by\n' +
  '`npm run build` (`server/esbuild.config.mjs`); do not edit it by hand.\n';
for (const name of [...packages.keys()].sort()) {
  const dir = packages.get(name);
  const meta = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const lic = licenseFile(dir);
  notices += `\n## ${name} ${meta.version}\n\nLicense: ${meta.license ?? 'see below'}\n`;
  if (meta.homepage || meta.repository) {
    const repo = typeof meta.repository === 'string' ? meta.repository : meta.repository?.url;
    notices += `Source: ${meta.homepage ?? repo}\n`;
  }
  if (lic) notices += '\n```text\n' + readFileSync(lic, 'utf8').replace(/\r\n/g, '\n').trim() + '\n```\n';
}
writeFileSync('../THIRD_PARTY_NOTICES.md', notices);
